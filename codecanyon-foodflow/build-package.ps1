<#
.SYNOPSIS
  Assembles the FoodFlow CodeCanyon submission package from the live Swado
  source tree, then zips it.

.WHY THIS SCRIPT EXISTS
  CodeCanyon's previous rejection (see ../codecanyon.txt) flagged disallowed
  folders in the package: vendor/, build/, and three "ephemeral" folders.
  Those are all build artifacts that get regenerated by `composer install`
  and `flutter pub get` / a Flutter build -- they should never ship in a
  source package, and copying them bloats the zip by hundreds of MB for
  nothing a buyer needs. This script explicitly whitelists source folders
  and excludes every known artifact/cache directory, rather than copying
  everything and trying to delete the bad parts afterward (which is how
  the disallowed folders got shipped last time -- an exclude-list applied
  late in the process is easy to miss one unexpected generated subfolder).

.USAGE
  Run from PowerShell:  .\build-package.ps1
  Produces:
    .\package\                 -- clean, unzipped submission contents
    .\FoodFlow-v1.0.0.zip       -- the file to upload to CodeCanyon
#>

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path $PSScriptRoot -Parent          # D:\karn\Swado
$Staging  = Join-Path $PSScriptRoot 'package'
$Version  = '1.0.0'
$ZipPath  = Join-Path $PSScriptRoot "FoodFlow-v$Version.zip"

# Directories that must NEVER appear in the package -- regenerated by the
# buyer's own `composer install` / `flutter pub get` / `flutter build`.
# This is the exact fix for the "build, vendor, ephemeral" rejection point.
$ExcludeDirs = @(
    'vendor', 'node_modules', 'build', 'ephemeral',
    '.dart_tool', '.gradle', '.git', '.idea', '.vscode',
    'storage\framework\cache', 'storage\framework\sessions', 'storage\framework\views',
    'bootstrap\cache', '.phpunit.cache'
)
# Files that must never ship -- real secrets or IDE noise.
# Also catches ad-hoc dumps/backups that accumulate in a working tree but
# were never meant to ship -- e.g. admin\app.7z (a stray 7z backup) and
# admin\inspect_data.php (an empty debug scratch file), both found in the
# first real package build and not caught by the original narrower list.
$ExcludeFiles = @('.env', '*.zip', '*.tar.gz', '*.tgz', '*.7z', '*.rar', '*.bak', '*.sql', '*.log', '.DS_Store', 'inspect_data.php')

function Copy-Clean {
    param([string]$Source, [string]$Dest)

    $xd = $ExcludeDirs | ForEach-Object { $_ }
    $xf = $ExcludeFiles | ForEach-Object { $_ }

    New-Item -ItemType Directory -Force -Path $Dest | Out-Null

    # robocopy exit codes 0-7 are all "success" (8+ means real failure)
    robocopy $Source $Dest /E /XD $xd /XF $xf /NFL /NDL /NJH /NJS /NC /NS /NP
    if ($LASTEXITCODE -ge 8) {
        throw "robocopy failed copying $Source -> $Dest (exit $LASTEXITCODE)"
    }
}

Write-Host "Cleaning previous staging output..." -ForegroundColor Cyan
if (Test-Path $Staging) { Remove-Item $Staging -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Staging | Out-Null

Write-Host "Copying admin panel (Laravel) source, excluding vendor/.env/caches..." -ForegroundColor Cyan
Copy-Clean -Source (Join-Path $RepoRoot 'admin') -Dest (Join-Path $Staging 'admin-panel')

# admin-panel ships .env.example only -- never a real .env. build-package
# copy above already excludes .env by pattern; this is a defense-in-depth
# check so a future change to the exclude list can't silently regress it.
$shippedEnv = Join-Path $Staging 'admin-panel\.env'
if (Test-Path $shippedEnv) {
    throw "SAFETY CHECK FAILED: a real .env file made it into the package at $shippedEnv -- fix the exclude list before continuing."
}

Write-Host "Copying Flutter apps, excluding build/ and ephemeral/..." -ForegroundColor Cyan
foreach ($app in @('customer', 'driver', 'restaurant', 'onboard')) {
    $src = Join-Path $RepoRoot $app
    if (Test-Path $src) {
        Copy-Clean -Source $src -Dest (Join-Path $Staging "apps\$app")
    } else {
        Write-Warning "Expected app folder not found, skipping: $src"
    }
}

Write-Host "Stamping FoodFlow branding onto the STAGED copies only (live Swado source is never touched)..." -ForegroundColor Cyan

$envExamplePath = Join-Path $Staging 'admin-panel\.env.example'
if (Test-Path $envExamplePath) {
    (Get-Content $envExamplePath) -replace '^APP_NAME=.*', 'APP_NAME=FoodFlow' | Set-Content $envExamplePath
}

$brandLabels = @{
    'customer'   = 'FoodFlow'
    'driver'     = 'FoodFlow Driver'
    'restaurant' = 'FoodFlow Partner'
    'onboard'    = 'FoodFlow Onboarding'
}
foreach ($app in $brandLabels.Keys) {
    $manifest = Join-Path $Staging "apps\$app\android\app\src\main\AndroidManifest.xml"
    if (Test-Path $manifest) {
        (Get-Content $manifest -Raw) -replace 'android:label="[^"]*"', ('android:label="' + $brandLabels[$app] + '"') |
            Set-Content $manifest -NoNewline
    }
    $iosPlist = Join-Path $Staging "apps\$app\ios\Runner\Info.plist"
    if (Test-Path $iosPlist) {
        (Get-Content $iosPlist -Raw) -replace '(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)', ('$1' + $brandLabels[$app] + '$2') |
            Set-Content $iosPlist -NoNewline
    }
}
Write-Host "Branding stamped: $($brandLabels.Values -join ', ')" -ForegroundColor Green

Write-Host "Copying documentation..." -ForegroundColor Cyan
Copy-Item (Join-Path $PSScriptRoot 'package\documentation') -Destination (Join-Path $Staging 'documentation') -Recurse -Force -ErrorAction SilentlyContinue
# (documentation is authored directly under package\documentation, so the
# line above is a no-op once that's already the staging path -- kept here
# so re-running this script after editing docs in place still works if the
# authoring location ever moves.)

Write-Host "Verifying no disallowed folders survived..." -ForegroundColor Cyan
$leftovers = Get-ChildItem -Path $Staging -Recurse -Directory -Force |
    Where-Object { $ExcludeDirs -contains $_.Name }
if ($leftovers) {
    $leftovers | ForEach-Object { Write-Warning "Disallowed folder still present: $($_.FullName)" }
    throw "Package failed the disallowed-folder check. Fix before zipping."
}
Write-Host "Clean -- no vendor/build/ephemeral/node_modules folders in the package." -ForegroundColor Green

Write-Host "Zipping to $ZipPath ..." -ForegroundColor Cyan
if (Test-Path $ZipPath) { Remove-Item $ZipPath -Force }
Compress-Archive -Path (Join-Path $Staging '*') -DestinationPath $ZipPath -CompressionLevel Optimal

$sizeMB = [math]::Round((Get-Item $ZipPath).Length / 1MB, 1)
Write-Host "Done: $ZipPath ($sizeMB MB)" -ForegroundColor Green
Write-Host "Screenshots and listing copy are NOT inside this zip -- CodeCanyon uploads those separately via the item listing form. See ..\screenshots\ and ..\listing\." -ForegroundColor Yellow

# robocopy's own exit codes (0-7 = success, with useful detail like "1 = files
# copied OK") otherwise leak through as this script's exit code, which looks
# like a failure to anything checking $LASTEXITCODE even though everything
# above completed correctly -- force a clean 0 now that we're actually done.
exit 0
